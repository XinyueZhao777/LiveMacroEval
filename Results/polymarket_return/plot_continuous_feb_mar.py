@dataclass(frozen=True)
class SegmentSpec:
    """Defines how to extract a segment's bets from the detail directory.

    Fields:
        label: short tag for logging / vertical guides ("feb", "mar").
        month_token: the token in detailed-CSV filenames
            (e.g. "2026-02" for the Feb CPI market, or "2026-Q1" for GDP).
        calendar_window: optional (start, end_exclusive) ISO timestamps
            applied as an additional filter on bet datetime_utc. Used for
            GDP, where the same Q1 CSV must be split into Feb / Mar pieces
            by calendar month rather than by source CSV.
        apply_shared_start: when True, drop bets earlier than the segment's
            shared start. When False, each model keeps its own first bet.
        shared_start_anchor: when set, the segment's shared start is pinned
            to this model's first bet in the segment (rather than max across
            all models). Used to anchor the March start to claude-sonnet-4.5
            because it is typically the latest model to start and we don't
            want to miss it on the chart.
    """

    label: str
    month_token: str
    calendar_window: tuple[str, str] | None
    apply_shared_start: bool
    shared_start_anchor: str | None = None


# Per the user's clarification:
#   * "earliest bet time for Feb and for Mar separately" -> per-segment logic.
#   * "for march, do not set a common start time" -> Feb has shared start,
#     March does not.
#   * "Include Feb-Mar window for GDP, ... use the prediction in feb and march
#     as theses are all prediction of Q1 2026 gdp" -> GDP uses calendar-month
#     filters on the single Q1 2026 CSV (which has been re-generated by
#     calculate_earnings.py to combine 2026-02 + 2026-03 prediction files).
# Default March anchor model. Can be overridden by --mar-anchor on the
# command line. Trade-off:
#   * "gpt-5-search-api" gives more March-window breathing room because
#     gpt-5 typically starts March bets earlier than claude-sonnet-4.5
#     (e.g. CPI/unemp Mar markets: gpt-5 ~Mar 26 vs claude-sonnet ~Apr 2).
#   * "claude-sonnet-4.5" guarantees claude-sonnet's first March bet is
#     visible from the start of the March segment (it's the latest-starting
#     important model, so anchoring to it loses the most data).
# Models whose first March bet is later than the anchor still appear on the
# chart from their own first bet onward; they just join later.
DEFAULT_MAR_ANCHOR_MODEL = "gpt-5-search-api"


