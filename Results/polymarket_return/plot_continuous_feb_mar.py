# Models excluded from these plots. Their CSVs are skipped at discovery so
# they don't show up in per-segment counts, the legend labels, or any of
# the downstream filters.
EXCLUDED_MODELS: set[str] = {"claude-code-agent"}


def discover_csvs_for_segment(detail_dir: Path, month_token: str) -> dict[str, Path]:
    """Find {model_name -> csv_path} for a given month token in detail_dir.

    Filename patterns produced by calculate_earnings.py:
      AI models : betting_results_<model>_<month>_hourly_latest.csv
      Fed models: betting_results_<model>_<month>_hourly.csv
    """
    out: dict[str, Path] = {}
    for path in detail_dir.glob(f"betting_results_*_{month_token}_hourly*.csv"):
        parts = path.stem.split("_")
        # Find the index of the month token; everything between
        # 'betting_results_' and '_<month>_' is the model name (which itself
        # may contain hyphens and digits, e.g. qwen3-235b-a22b-instruct-2507).
        try:
            month_idx = parts.index(month_token)
        except ValueError:
            continue
        if month_idx <= 2:
            continue
        model = "_".join(parts[2:month_idx])
        if model in EXCLUDED_MODELS:
            continue
        out[model] = path
    return out


def load_bet_csv(path: Path) -> pd.DataFrame:
    """Load only the columns needed for cumulative-return computation."""
    df = pd.read_csv(path, parse_dates=["datetime_utc"])
    keep = ["datetime_utc", "bet_amount", "shares_bought", "is_winning_bet"]
    return df[keep].sort_values("datetime_utc").reset_index(drop=True)


def cumulative_series(bets_df: pd.DataFrame) -> pd.DataFrame:
    """Compute cumulative invested / profit / return-% at every bet timestamp.

    Mirrors `calculate_cumulative_returns_series` in calculate_earnings.py:
      - $bet_amount added to invested at every bet
      - winning bets immediately credit `shares_bought` to value (each winning
        share pays $1 at resolution)
      - return_pct = (value - invested) / invested * 100

    NOTE: this function is also where the Feb→March carry-over happens —
    it accumulates straight through, with no reset between segments because
    `bets_df` here is already the per-model concatenation of all segments
    (built in `build_per_model_continuous_series`). Carries the per-bet
    `segment` label through to the cumulative rows so plotting can compute
    stitched relative-time x-coordinates.
    """
    inv = 0.0
    val = 0.0
    rows = []
    has_segment = "segment" in bets_df.columns
    for _, r in bets_df.iterrows():
        inv += float(r["bet_amount"])
        if bool(r["is_winning_bet"]):
            val += float(r["shares_bought"])
        prof = val - inv
        ret = (prof / inv * 100.0) if inv > 0 else 0.0
        row = {
            "datetime_utc": r["datetime_utc"],
            "cumulative_invested": inv,
            "cumulative_profit": prof,
            "cumulative_return_pct": ret,
        }
        if has_segment:
            row["segment"] = r["segment"]
        rows.append(row)
    return pd.DataFrame(rows)


def build_per_model_continuous_series(
    detail_dir: Path,
    segments: list[SegmentSpec],
) -> tuple[
    dict[str, pd.DataFrame],
    dict[str, pd.Timestamp | None],
    dict[str, dict[str, Path]],
    dict[str, dict[str, pd.Timestamp]],
]:
    """For each model, build the concatenated bets across segments.

    Returns:
        model_concat_bets   : {model -> bets_df concatenated across segments}
        segment_starts      : {segment_label -> shared_start_timestamp or None}
                              (None when the segment uses no shared start, OR
                              when no models had bets in that segment)
        per_segment_paths   : {segment_label -> {model -> csv_path}} (logging)
        segment_contrib     : {segment_label -> {model -> first_kept_ts}}
                              models whose bets actually landed in this
                              segment after calendar + shared-start filters.
    """
    per_segment_paths: dict[str, dict[str, Path]] = {
        seg.label: discover_csvs_for_segment(detail_dir, seg.month_token)
        for seg in segments
    }

    # Load bets per (segment, model), applying any segment-level calendar
    # filter. Calendar windows are needed for GDP, where the same Q1 CSV
    # supplies both Feb and Mar segments.
    segment_bets: dict[str, dict[str, pd.DataFrame]] = {}
    for seg in segments:
        bets_by_model: dict[str, pd.DataFrame] = {}
        for model, path in per_segment_paths[seg.label].items():
            bdf = load_bet_csv(path)
            if seg.calendar_window is not None:
                start_ts = pd.Timestamp(seg.calendar_window[0])
                end_ts_excl = pd.Timestamp(seg.calendar_window[1])
                bdf = bdf[
                    (bdf["datetime_utc"] >= start_ts) & (bdf["datetime_utc"] < end_ts_excl)
                ].reset_index(drop=True)
            if not bdf.empty:
                bets_by_model[model] = bdf
        segment_bets[seg.label] = bets_by_model

    # Compute the shared start per segment, only when the segment opted in.
    segment_starts: dict[str, pd.Timestamp | None] = {}
    for seg in segments:
        if not seg.apply_shared_start:
            segment_starts[seg.label] = None
            continue
        if seg.shared_start_anchor is not None:
            # Pinned to a specific model's first bet (e.g. claude-sonnet-4.5
            # for March across all variables).
            anchor_bets = segment_bets[seg.label].get(seg.shared_start_anchor)
            if anchor_bets is None or anchor_bets.empty:
                raise ValueError(
                    f"Segment '{seg.label}' is anchored to "
                    f"{seg.shared_start_anchor!r} but that model has no bets "
                    f"in this segment for month_token={seg.month_token!r}."
                )
            segment_starts[seg.label] = anchor_bets["datetime_utc"].iloc[0]
        else:
            first_times = [bdf["datetime_utc"].iloc[0] for bdf in segment_bets[seg.label].values()]
            # Shared start = LATEST first-bet across models present in segment,
            # so every such model has at least one bet at or before this time.
            segment_starts[seg.label] = max(first_times) if first_times else None

    all_models: set[str] = set()
    for bets in segment_bets.values():
        all_models.update(bets.keys())

    model_concat_bets: dict[str, pd.DataFrame] = {}
    segment_contrib: dict[str, dict[str, pd.Timestamp]] = {seg.label: {} for seg in segments}
    for model in sorted(all_models):
        pieces: list[pd.DataFrame] = []
        # Iterate segments in declared order so cumulative invested/profit
        # accumulates Feb -> Mar (carry-over).
        for seg in segments:
            bets = segment_bets[seg.label].get(model)
            if bets is None or bets.empty:
                continue
            shared_start = segment_starts.get(seg.label)
            if shared_start is not None:
                # Drop bets before the shared start so all models in this
                # segment line up at the same starting timestamp.
                kept = bets[bets["datetime_utc"] >= shared_start]
            else:
                # No shared start: every model keeps its own first bet.
                kept = bets
            if not kept.empty:
                # Tag each row with its segment label so the plot can compute
                # a stitched (gap-free) x-coordinate per segment.
                kept = kept.assign(segment=seg.label)
                pieces.append(kept)
                segment_contrib[seg.label][model] = kept["datetime_utc"].iloc[0]
        if pieces:
            seg_order = {seg.label: i for i, seg in enumerate(segments)}
            combined = pd.concat(pieces, ignore_index=True)
            # Enforce segment-then-time ordering so Feb cumulative is always
            # accumulated before Mar (carry-over), even if a Mar timestamp
            # somehow precedes a Feb one.
            combined["_seg_order"] = combined["segment"].map(seg_order)
            model_concat_bets[model] = (
                combined
                .sort_values(["_seg_order", "datetime_utc"])
                .drop(columns="_seg_order")
                .reset_index(drop=True)
            )

    return model_concat_bets, segment_starts, per_segment_paths, segment_contrib


def compute_segment_extents(
    model_bets: dict[str, pd.DataFrame],
    segments: list[SegmentSpec],
    segment_starts: dict[str, pd.Timestamp | None],
) -> dict[str, float]:
    """For each segment, compute its on-screen extent in days.

    The extent runs from the segment's shared start (or the segment's earliest
    kept bet, when no shared start was set) to the latest kept bet across
    all models. This determines how wide the segment looks on the stitched
    x-axis.
    """
    extents: dict[str, float] = {}
    for seg in segments:
        last_bets: list[pd.Timestamp] = []
        for bets in model_bets.values():
            seg_rows = bets[bets["segment"] == seg.label]
            if not seg_rows.empty:
                last_bets.append(seg_rows["datetime_utc"].iloc[-1])
        if not last_bets:
            extents[seg.label] = 0.0
            continue
        seg_end = max(last_bets)
        seg_start = segment_starts.get(seg.label)
        if seg_start is None:
            # Segment without a shared start: anchor extent at its earliest
            # kept bet across models.
            first_bets = [
                bets[bets["segment"] == seg.label]["datetime_utc"].iloc[0]
                for bets in model_bets.values()
                if not bets[bets["segment"] == seg.label].empty
            ]
            seg_start = min(first_bets) if first_bets else seg_end
        extents[seg.label] = (seg_end - seg_start).total_seconds() / 86400.0
    return extents


def stitched_x_for_row(
    ts: pd.Timestamp,
    seg_label: str,
    segments: list[SegmentSpec],
    segment_starts: dict[str, pd.Timestamp | None],
    extents: dict[str, float],
    gap_days: float,
) -> float:
    """Map a (timestamp, segment) pair to a stitched-timeline x in days.

    Each segment occupies `extents[seg]` days on the axis. A small `gap_days`
    visual spacer separates consecutive segments, replacing the (potentially
    multi-week) empty period between e.g. the Feb market resolving and the
    March market opening. Within a segment, x is the time elapsed since that
    segment's shared start (so the x-axis reads as relative time per segment).
    """
    cumulative_offset = 0.0
    for seg in segments:
        seg_start = segment_starts.get(seg.label)
        if seg.label == seg_label:
            if seg_start is None:
                # Should not happen with our current configs, but guard anyway.
                return cumulative_offset
            return cumulative_offset + (ts - seg_start).total_seconds() / 86400.0
        cumulative_offset += extents.get(seg.label, 0.0) + gap_days
    raise ValueError(f"Unknown segment label {seg_label!r}")


def daily_step_forward(
    x: np.ndarray,
    y: np.ndarray,
) -> tuple[np.ndarray, np.ndarray]:
    """Step-forward sample of y at each integer x (one point per day).

    For a cumulative time series sampled at irregular bet timestamps,
    this returns the value of y at each integer day d, defined as the
    value of the latest sample with x <= d (i.e. the cumulative state at
    end-of-day d). This makes hourly models (GPT) and daily / weekly
    models (Fed nowcasts) share the same point cadence (one per day),
    so their smoothed curves and markers land at the same frequency.

    Grid runs ceil(x[0]) .. ceil(x[-1]) so the line visually extends to
    the final observation. Days before the model's first sample are
    dropped (we never extrapolate backwards).
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    if len(x) == 0:
        return x, y
    order = np.argsort(x)
    x, y = x[order], y[order]
    day_start = int(np.ceil(x[0]))
    day_end = int(np.ceil(x[-1]))
    if day_end < day_start:
        return x, y
    days = np.arange(day_start, day_end + 1, dtype=float)
    idx = np.searchsorted(x, days, side="right") - 1
    valid = idx >= 0
    return days[valid], y[idx[valid]]


def smooth_xy(
    x: np.ndarray,
    y: np.ndarray,
    num_points: int = 300,
    presmooth_window_days: int = 1,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Daily-resample (x, y), fit a smoothing spline, return dense curve + per-day markers.

    Returns ``(x_dense, y_dense_smoothed, x_daily, y_daily_on_curve)``,
    where ``(x_dense, y_dense_smoothed)`` is the smoothed curve evaluated
    on a fine grid for line drawing, and ``(x_daily, y_daily_on_curve)``
    is the same spline evaluated at integer days for marker placement.
    Markers therefore sit ON the smoothed curve and at the same daily
    cadence regardless of how often the underlying model bets.

    Uses ``scipy.interpolate.make_smoothing_spline`` with the smoothing
    parameter chosen automatically by generalized cross-validation
    (``lam=None``), per the scipy smoothing-splines tutorial:
    https://docs.scipy.org/doc/scipy/tutorial/interpolate/smoothing_splines.html

    Optional ``presmooth_window_days`` applies a centered rolling mean of
    that many days to the step-forward daily values BEFORE the spline is
    fit. The GCV used by ``make_smoothing_spline`` picks a looser
    smoothing parameter as the number of input samples grows; on variables
    with much longer spans (e.g. GDP's ~60-day window vs CPI's ~25-day),
    this manifests as a wigglier curve. Pre-averaging the daily values
    shrinks the effective sample count seen by GCV, bringing the visual
    smoothness back in line with the shorter-span variables. Default of 1
    is a no-op (identity), so the pipeline is unchanged for variables that
    don't opt in.

    Fallbacks:
      * If no integer days span the data at all, returns the deduped raw
        polyline for both the curve and the markers.
      * If fewer than 4 daily points are available (cubic spline needs
        >= 4), returns the raw daily polyline for both.
    """
    days, y_daily = daily_step_forward(x, y)
    if len(days) == 0:
        df = (
            pd.DataFrame({"x": np.asarray(x, dtype=float), "y": np.asarray(y, dtype=float)})
            .groupby("x", as_index=False)
            .mean()
            .sort_values("x")
        )
        xu = df["x"].to_numpy()
        yu = df["y"].to_numpy()
        return xu, yu, xu, yu
    if presmooth_window_days > 1 and len(y_daily) >= 2:
        y_daily = (
            pd.Series(y_daily)
            .rolling(window=presmooth_window_days, center=True, min_periods=1)
            .mean()
            .to_numpy()
        )
    if len(days) < 4:
        return days, y_daily, days, y_daily
    spline = make_smoothing_spline(days, y_daily)
    x_dense = np.linspace(days[0], days[-1], num_points)
    y_dense = spline(x_dense)
    # GCV (lam=None) over-smooths short, near-monotone series: with ~9 daily
    # points and no large jumps, the GCV-chosen lambda collapses the spline
    # to an effectively straight line (observed on claude-sonnet-4.5 for
    # unemployment, where max|2nd diff| of the GCV curve was ~0.012 against
    # a 174% data range — curvature ratio < 1e-4). Detect this case by the
    # GCV curve's curvature ratio and fall back to a monotone-preserving
    # PCHIP interpolation, which tracks the daily values without overshoot.
    # A fixed lambda is not used here because what's right for sonnet
    # (lam~1) flattens GPT-5's −100→+68 jump in the same plot.
    data_range = float(y_daily.max() - y_daily.min())
    if data_range > 1.0:
        gcv_curv = float(np.max(np.abs(np.diff(y_dense, 2))))
        if gcv_curv / data_range < 5e-4:
            pchip = PchipInterpolator(days, y_daily)
            return x_dense, pchip(x_dense), days, pchip(days)
    return x_dense, y_dense, days, spline(days)


def relax_label_positions(ys: list[float], min_gap: float) -> list[float]:
    """Push label positions apart so each adjacent pair differs by >= min_gap.

    Input must be sorted ascending. Pushes bidirectionally (half the
    deficit goes to each side) so labels are not all shoved up or down,
    and iterates until no overlaps remain. Used to lay out end-of-line
    model labels when several models finish with near-identical returns
    (e.g. all near 0%).
    """
    n = len(ys)
    if n <= 1:
        return list(ys)
    adjusted = list(ys)
    for _ in range(200):
        moved = False
        for i in range(n - 1):
            gap = adjusted[i + 1] - adjusted[i]
            if gap < min_gap - 1e-9:
                push = (min_gap - gap) / 2.0
                adjusted[i] -= push
                adjusted[i + 1] += push
                moved = True
        if not moved:
            break
    return adjusted


def plot_variable(
    variable: str,
    detail_dir: Path,
    output_dir: Path,
    variable_segments: dict[str, list[SegmentSpec]],
    filename_suffix: str = "",
    gap_days: float = 0.5,
    presmooth_window_days: int = 1,
) -> None:
    segments = variable_segments[variable]
    model_bets, segment_starts, per_segment_paths, segment_contrib = (
        build_per_model_continuous_series(detail_dir, segments)
    )

    print("  Models with CSVs discovered per segment (raw, pre-filter):")
    for seg in segments:
        discovered = sorted(per_segment_paths.get(seg.label, {}).keys())
        print(f"    [{seg.label}] {len(discovered)}: {discovered}")
    print("  Models actually contributing bets per segment (post-filter):")
    for seg in segments:
        contribs = sorted(segment_contrib[seg.label].keys())
        print(f"    [{seg.label}] {len(contribs)}: {contribs}")
    print("  Per-segment shared start (UTC):")
    for seg in segments:
        start = segment_starts.get(seg.label)
        anchor_note = ""
        if seg.apply_shared_start and seg.shared_start_anchor is not None:
            anchor_note = f" (anchored to {seg.shared_start_anchor})"
        print(f"    [{seg.label}] {start}{anchor_note}")

    if not model_bets:
        print(f"  No usable bet data for {variable}; skipping plot.")
        return

    extents = compute_segment_extents(model_bets, segments, segment_starts)
    print("  Per-segment on-screen extent (days):")
    for seg in segments:
        print(f"    [{seg.label}] {extents.get(seg.label, 0.0):.2f}")

    # ── Stitched x-axis layout (used by plot loop, dividers, ticks, xlim) ──
    # seg_offsets[seg] is where each segment begins on the stitched x-axis;
    # total_x is the span from the start of the first segment to the end of
    # the last segment (the inter-segment gap is included between but not
    # past the final segment).
    seg_offsets: dict[str, float] = {}
    cum = 0.0
    for seg in segments:
        seg_offsets[seg.label] = cum
        cum += extents.get(seg.label, 0.0) + gap_days
    total_x = cum - gap_days

    # Wide-and-short figure so three of these stack cleanly into a single
    # column (one per variable). Width 17" gives the long GDP timeline room
    # to breathe without cramping the end-of-line model labels.
    fig, ax = plt.subplots(figsize=(17, 5.5), facecolor="white")
    ax.set_facecolor("white")

    series_records: list[pd.DataFrame] = []
    final_summaries: list[tuple[str, float, float, int]] = []
    # End-of-line label data, accumulated during the plotting loop and used
    # below to draw model-name labels next to each curve (instead of a panel
    # legend), with overlap-avoidance for models whose final returns coincide.
    plotted_models: list[dict] = []

    for model in sorted(model_bets.keys()):
        bets = model_bets[model]
        series = cumulative_series(bets)
        if series.empty:
            continue

        # Compute stitched (gap-removed, relative-time) x for each row.
        x_values = [
            stitched_x_for_row(ts, seg, segments, segment_starts, extents, gap_days)
            for ts, seg in zip(series["datetime_utc"], series["segment"])
        ]
        series = series.assign(stitched_x_days=x_values)

        style = MODEL_STYLES.get(
            model,
            {"color": "#666666", "linestyle": "-", "marker": "o", "label": model},
        )

        # One spline per model across the full stitched series (Feb + Mar
        # together) after step-forward daily resampling. Daily resampling
        # makes hourly (GPT) and daily/weekly (Fed) models share the same
        # point cadence so their smoothed curves and markers look the same
        # frequency. Markers are evaluated on the smoothed curve at integer
        # days so they sit on the line at uniform daily spacing.
        x_dense, y_smooth, _x_marker, _y_marker = smooth_xy(
            series["stitched_x_days"].to_numpy(),
            series["cumulative_return_pct"].to_numpy(),
            presmooth_window_days=presmooth_window_days,
        )
        if len(x_dense) == 0:
            continue
        ax.plot(
            x_dense,
            y_smooth,
            linewidth=3,
            color=style["color"],
            linestyle=style["linestyle"],
            marker="None",
            label=style["label"],
        )
        plotted_models.append({
            "label": style["label"],
            "color": style["color"],
            "x_end": float(x_dense[-1]),
            "y_end": float(y_smooth[-1]),
        })

        final_return = float(series["cumulative_return_pct"].iloc[-1])
        total_invested = float(series["cumulative_invested"].iloc[-1])
        total_bets = int(len(series))
        final_summaries.append((style["label"], final_return, total_invested, total_bets))

        out_series = series.copy()
        out_series.insert(0, "model", model)
        series_records.append(out_series)

    ax.axhline(y=0, color="#333333", linestyle="-", linewidth=1, alpha=0.6)

    # Place a small fixed number of ticks at VISUALLY equal positions across
    # the stitched x-axis. The earlier approach put ticks at integer-day
    # positions within each segment, which made the inter-segment visual gap
    # (gap_days) plus each segment's fractional extent appear as an uneven
    # step at the Feb→Mar boundary. Each tick is labeled by mapping its
    # stitched-x back through the segments using carry-over day numbering
    # (Mar day 0 = label int(ext_feb)+1), so labels still read as "days
    # since Feb-target nowcasting start"; small label-jump irregularities
    # at the segment boundary are unavoidable because of the visual gap.
    N_TICKS = 6
    tick_positions = list(np.linspace(0, total_x, N_TICKS))
    tick_labels: list[str] = []
    for p in tick_positions:
        offset_days = 0
        day_label: float = 0.0
        for i, seg in enumerate(segments):
            ext = extents.get(seg.label, 0.0)
            if ext <= 0:
                continue
            seg_off = seg_offsets[seg.label]
            if p <= seg_off + ext + 1e-6:
                day_label = offset_days + max(0.0, p - seg_off)
                break
            # Position falls in the inter-segment visual gap: snap label
            # to the end of the current segment.
            if i + 1 < len(segments) and p < seg_offsets[segments[i + 1].label]:
                day_label = offset_days + ext
                break
            offset_days += int(ext) + 1
        else:
            day_label = offset_days
        tick_labels.append(f"+{int(round(day_label)):02d}")
    ax.set_xticks(tick_positions)
    ax.set_xticklabels(tick_labels, rotation=0, ha="center", fontsize=14)

    title_var = VARIABLE_TITLES.get(variable, variable)
    # Title is just the variable name (per user request). The previous
    # multi-line subtitle and the per-segment calendar-start captions were
    # dropped to keep the plot uncluttered when three of these are
    # stacked together.
    ax.set_title(title_var)
    ax.set_xlabel("Days since nowcasting start")
    ax.set_ylabel("Cumulative Return (%)")
    ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda x, _: f"{x:.0f}%"))
    # End-of-line model labels (instead of a panel legend). Labels are
    # placed near each curve's terminal point, sorted by y and bidirectionally
    # relaxed so models with overlapping final returns (e.g. several near 0%)
    # don't collide. A thin colored leader connects each label to its line.
    label_text_objs: list = []
    if plotted_models:
        ymin, ymax = ax.get_ylim()
        yrange = ymax - ymin if ymax > ymin else 1.0
        # Min vertical spacing between adjacent labels, in y-axis (percent)
        # units. Scaled to the current y-range so it adapts to plots with
        # tight (-5%..+5%) vs wide (-50%..+200%) cumulative-return spans.
        # Tuned for the 14pt label font and 5.5"-tall figure used here.
        # ~8% of the y-range gives roughly 0.44" of vertical separation
        # per label — enough that 4 labels clustered at the same value
        # (e.g. four models stuck at -100% in the unemp plot) don't
        # collide AND the relaxed bottom label sits well above the
        # axis floor after the y-limit expansion below.
        min_gap = max(yrange * 0.08, 4.0)

        ordered = sorted(plotted_models, key=lambda m: m["y_end"])
        adjusted_ys = relax_label_positions([m["y_end"] for m in ordered], min_gap)

        x_end_max = max(m["x_end"] for m in plotted_models)
        leader_end_x = x_end_max + 0.4
        label_x = leader_end_x + 0.2

        for m, y_label in zip(ordered, adjusted_ys):
            ax.plot(
                [m["x_end"], leader_end_x],
                [m["y_end"], y_label],
                color=m["color"], linewidth=0.9, alpha=0.6, linestyle="-",
                solid_capstyle="round",
            )
            txt = ax.text(
                label_x, y_label, m["label"],
                color=m["color"], fontsize=14,
                ha="left", va="center",
            )
            label_text_objs.append(txt)

        # Expand y-limits if relaxed label positions ran past the original
        # data range (likely when many models clustered around the same y).
        # Buffer scales with y-range so the lowest/highest labels don't
        # sit right at the axis spine after relaxation.
        ylim_pad = max(yrange * 0.03, 2.0)
        new_ymin = min(ymin, min(adjusted_ys) - ylim_pad)
        new_ymax = max(ymax, max(adjusted_ys) + ylim_pad)
        ax.set_ylim(new_ymin, new_ymax)
        # Initial xlim — wide enough that labels render without clipping
        # before tight_layout positions the axes. We will tighten this
        # after rendering by measuring actual label bboxes.
        ax.set_xlim(-0.5, total_x + max(6.5, total_x * 0.18))
    else:
        ax.set_xlim(-0.5, total_x + 0.5)

    plt.tight_layout()

    # ── Tight xlim, measured from rendered label widths ───────────────────
    # After tight_layout has positioned the axes, query the rendered text
    # bboxes for the end-of-line labels and solve algebraically for the
    # smallest xlim_right that keeps the longest label's right edge
    # `pad_pixels` inside the axes. Replaces the prior fixed margin
    # (max(6.5, total_x*0.18)), which over-padded short-span variables
    # like unemployment.
    if label_text_objs:
        fig.canvas.draw()
        renderer = fig.canvas.get_renderer()
        ax_pixel_width = ax.get_window_extent(renderer=renderer).width
        xlim_left, _ = ax.get_xlim()
        pad_pixels = 6.0
        required_ranges: list[float] = []
        for txt in label_text_objs:
            bbox = txt.get_window_extent(renderer=renderer)
            denom = ax_pixel_width - pad_pixels - bbox.width
            if denom <= 0:
                continue  # label wider than axes; can't fit cleanly
            label_x_data = float(txt.get_position()[0])
            required_ranges.append(
                (label_x_data - xlim_left) * ax_pixel_width / denom
            )
        if required_ranges:
            ax.set_xlim(xlim_left, xlim_left + max(required_ranges))

    plot_path = output_dir / f"continuous_returns_{variable}{filename_suffix}.png"
    plt.savefig(plot_path, dpi=300, bbox_inches="tight", facecolor="white")
    plt.close()
    print(f"  Saved plot: {plot_path}")

    if series_records:
        all_series = pd.concat(series_records, ignore_index=True)
        csv_path = output_dir / f"continuous_returns_{variable}{filename_suffix}.csv"
        all_series.to_csv(csv_path, index=False)
        print(f"  Saved series CSV: {csv_path}")

    print(f"  Final returns ({variable}):")
    final_summaries.sort(key=lambda x: x[1], reverse=True)
    for label, final_ret, inv, n in final_summaries:
        print(f"    {label:30s} {final_ret:8.1f}%   (${inv:.0f}, {n} bets)")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Plot continuous Feb–Mar 2026 cumulative returns across models",
    )
    parser.add_argument(
        "--input-dir",
        default="polymarket_return/results/bet_hourly_latest_Apr26",
        help=(
            "Root containing per-variable detailed CSVs at "
            "<input-dir>/<variable>/hourly_latest/"
        ),
    )
    parser.add_argument(
        "--output-base",
        default="polymarket_return",
        help="Where to create feb_mar_continuous_<YYYYMMDD>/ output folder",
    )
    parser.add_argument(
        "--datestamp",
        default=None,
        help="Override the YYYYMMDD datestamp in the output folder name",
    )
    parser.add_argument(
        "--variables",
        nargs="+",
        default=list(VARIABLE_SEGMENTS.keys()),
        choices=list(VARIABLE_SEGMENTS.keys()),
        help="Which variables to plot",
    )
    parser.add_argument(
        "--mar-anchor",
        default=DEFAULT_MAR_ANCHOR_MODEL,
        help=(
            "Model name whose first March bet defines the March shared start "
            "(e.g. 'gpt-5-search-api' or 'claude-sonnet-4.5'). The anchor "
            "name is appended to output filenames so multiple anchors can "
            "coexist in the same output folder."
        ),
    )
    parser.add_argument(
        "--filename-suffix",
        default=None,
        help=(
            "Override the filename suffix (default: '_mar-anchor-<model>')."
        ),
    )
    args = parser.parse_args()

    input_dir = Path(args.input_dir)
    if not input_dir.exists():
        raise FileNotFoundError(f"Input directory not found: {input_dir}")

    datestamp = args.datestamp or datetime.now().strftime("%Y%m%d")
    output_dir = Path(args.output_base) / f"feb_mar_continuous_{datestamp}"
    output_dir.mkdir(parents=True, exist_ok=True)

    variable_segments = make_variable_segments(args.mar_anchor)
    suffix = (
        args.filename_suffix
        if args.filename_suffix is not None
        else f"_mar-anchor-{args.mar_anchor}"
    )

    print(f"Output directory: {output_dir}")
    print(f"Input directory : {input_dir}")
    print(f"March anchor    : {args.mar_anchor}")
    print(f"Filename suffix : {suffix}")

    configure_style()

    for variable in args.variables:
        print(f"\n=== {variable} ===")
        detail_dir = input_dir / variable / "hourly_latest"
        if not detail_dir.exists():
            print(f"  Missing detail directory: {detail_dir} (skipping)")
            continue
        plot_variable(
            variable,
            detail_dir,
            output_dir,
            variable_segments=variable_segments,
            filename_suffix=suffix,
            presmooth_window_days=VARIABLE_PRESMOOTH_DAYS.get(variable, 1),
        )

    print(f"\nDone. Plots and series CSVs in {output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
