#!/usr/bin/env python3
"""Continuous Feb–Mar 2026 cumulative-returns plots, one per variable.

Reads the per-month detailed bet CSVs already produced by
`calculate_earnings.py` (under
`Results/polymarket_return/results/bet_hourly_latest_Apr26/<var>/hourly_latest/`)
and stitches them into a single timeline with Feb→March carry-over.

Variables and their underlying betting markets:

  cpi_yoy            -> Feb 2026 CPI market + March 2026 CPI market
                        (one detailed CSV per market per model)
  unemployment_rate  -> Feb 2026 unemp market + March 2026 unemp market
  real_gdp_qoq       -> Q1 2026 GDP market (one quarterly market). Because
                        there's no separate Feb/Mar GDP market, the single
                        Q1 detailed CSV is calendar-split into Feb and Mar
                        segments here.

Two pieces of logic are explicit in the implementation:

  1. **Feb→March carry-over**: per-model bets are concatenated in time order
     across segments, and `cumulative_invested` / `cumulative_value` are
     accumulated WITHOUT any reset at the Feb→March boundary. The cumulative
     return-% therefore continues from the Feb ending value into March (see
     `cumulative_series` and the per-model concat in
     `build_per_model_continuous_series`).

  2. **Shared start time, only for the Feb segment**:
       * Feb segment: shared_start = max(first_bet_time) across the models
         that have data in the Feb segment, and bets earlier than that are
         dropped for every model. This standardizes the Feb start time as
         requested.
       * March segment: NO shared start is applied — each model's March bets
         start at that model's own first March bet (per the user request:
         "for march, do not set a common start time based on all the models,
         just directly start betting when the first march prediction is
         available").

Outputs (under `<output-base>/feb_mar_continuous_<YYYYMMDD>/`):
  - continuous_returns_<variable>.png   (one plot per variable, all models)
  - continuous_returns_<variable>.csv   (long-format cumulative series)

Conda env: livemacro.

Usage:
  python polymarket_return/plot_continuous_feb_mar.py \
    --input-dir polymarket_return/results/bet_hourly_latest_Apr26 \
    --output-base polymarket_return
"""

